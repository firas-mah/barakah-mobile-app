    /** Which act a block is. Custom blocks fall back to their area (Category). */
    fun actFor(block: Block, staysUntilAsr: Boolean = false): Act = when (block.templateId) {
        "fajr" -> Act.FAJR
        "dhuhr" -> if (staysUntilAsr) Act.DHUHR_STAY else Act.DHUHR
        "asr" -> Act.ASR
        "maghrib" -> Act.MAGHRIB
        "isha" -> Act.ISHA
        "jumuah" -> Act.JUMUAH
        "ghusl" -> Act.GHUSL
        "adhkar_fri" -> Act.KAHF
        "tahajjud" -> Act.TAHAJJUD
        "adhkar_am" -> Act.QURAN_ADHKAR
        "lunch", "lunch_fri" -> Act.MEAL
        "breakfast" -> Act.HEALTH
        "review", "weekly_review" -> Act.REVIEW
        "brand" -> Act.SPEECH
        "recovery" -> Act.REST
        "sleep" -> Act.SLEEP
        else -> when {
            block.kind == Kind.SLEEP -> Act.SLEEP
            block.kind == Kind.FRIENDS -> Act.FRIENDS
            else -> when (block.category) {
                Category.DEEN -> if (block.kind == Kind.PRAYER) Act.PRAYER_SOON else Act.QURAN_ADHKAR
                Category.BUILD -> Act.WORK
                Category.GROW -> Act.MARKETING
                Category.BRAND -> Act.SPEECH
                Category.LEARN -> Act.LEARN
                Category.HEALTH -> Act.HEALTH
                Category.FAMILY -> Act.FAMILY
                Category.SOCIAL -> Act.FRIENDS
                Category.REST -> Act.REST
            }
        }
    }

    /**
     * Picks one reminder for this act on this date. Changes every day, and [salt]
     * (e.g. the block's start hour) makes two blocks of the same act differ on the same day.
     */
    fun pick(act: Act, date: LocalDate, salt: Int = 0): Reminder {
        val list = BANK[act] ?: BANK.getValue(Act.GENERAL)
        val i = ((date.toEpochDay() + salt) % list.size + list.size) % list.size
        return list[i.toInt()]
    }

    fun forBlock(block: Block, date: LocalDate, staysUntilAsr: Boolean = false): Reminder =
        pick(actFor(block, staysUntilAsr), date, block.start.hour)
}
