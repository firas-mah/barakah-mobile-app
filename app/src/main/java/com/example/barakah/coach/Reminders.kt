/**
 * An ayah or a hadith matched to what you are about to do — always in Arabic.
 * Quran: exact text with its surah and ayah. Hadith: the well-known wording with its collection
 * and number (sunnah.com numbering). Where the grading matters it is written in the reference.
 */
data class Reminder(val text: String, val source: String, val quran: Boolean) {
    /** The text with the right brackets: ﴿ ﴾ for the Quran, « » for hadith. */
    val body: String get() = if (quran) "﴿$text﴾" else "«$text»"

    /** The reference: [السورة: الآية] for the Quran, رواه … for hadith. */
    val reference: String get() = if (quran) "[$source]" else source

    /** One paragraph, ready for a notification. */
    fun format(): String = "$body $reference"
}

private fun q(text: String, source: String) = Reminder(text, source, quran = true)
private fun h(text: String, source: String) = Reminder(text, source, quran = false)

